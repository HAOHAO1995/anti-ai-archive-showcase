import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {checkContent} from './lib/check-content.mjs';
import {checkGenealogy} from './lib/check-genealogy.mjs';
import {checkGenealogyIllustrations} from './lib/check-genealogy-illustrations.mjs';
import {checkTopics} from './lib/check-topics.mjs';
import {checkHistoryEssays} from './lib/check-history-essays.mjs';
const root=new URL('../',import.meta.url);
const data=JSON.parse(await readFile(new URL('lib/data/archive.json',root),'utf8'));
const catalog=JSON.parse(await readFile(new URL('lib/data/i18n/translations.json',root),'utf8'));
const genealogy=checkGenealogy(JSON.parse(await readFile(new URL('lib/data/genealogy.json',root),'utf8')));
const illustrations=checkGenealogyIllustrations(JSON.parse(await readFile(new URL('lib/data/genealogy-illustrations.json',root),'utf8')),JSON.parse(await readFile(new URL('lib/data/genealogy.json',root),'utf8')));
const archive=checkContent(data,catalog);
const topics=checkTopics(JSON.parse(await readFile(new URL('lib/data/topics.json',root),'utf8')),data);
const essays=checkHistoryEssays(JSON.parse(await readFile(new URL('lib/data/genealogy-essays.json',root),'utf8')),JSON.parse(await readFile(new URL('lib/data/genealogy.json',root),'utf8')));
const report={checkedAt:new Date().toISOString(),...archive,genealogy:genealogy.counts,topics:topics.counts,illustrations:illustrations.counts,essays:essays.counts,errors:[...essays.errors,...illustrations.errors,...archive.errors,...genealogy.errors,...topics.errors]};
await mkdir(new URL('maintenance/',root),{recursive:true});
await writeFile(new URL('maintenance/content-check.json',root),JSON.stringify(report,null,2));
console.log(JSON.stringify({...report,errors:report.errors.slice(0,20)},null,2));
if(report.errors.length)process.exitCode=1;
